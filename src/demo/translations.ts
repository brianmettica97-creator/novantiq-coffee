/** Traducciones de la demo con las claves reales (ids) de la organización. */
export function demoTranslations(bundle: OrganizationBundle): Translations {
  const en: Record<string, string> = {};
  const pt: Record<string, string> = {};
  for (const g of translatableGroups(bundle)) {
    for (const e of g.entries) {
      const t = T[e.source];
      if (!t) continue;
      en[e.key] = t[0];
      pt[e.key] = t[1];
    }
  }
  return { en, pt };
}
