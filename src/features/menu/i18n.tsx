const STRINGS: Record<MenuLanguage, Record<StringKey, string>> = { es, en, pt };

export type Translate = (key: StringKey, vars?: Record<string, string | number>) => string;

export function makeT(lang: MenuLanguage): Translate {
  const dict = STRINGS[lang];
  return (key, vars) => {
    let s = dict[key] ?? es[key];
    if (vars) for (const [k, v] of Object.entries(vars)) s = s.split(`{${k}}`).join(String(v));
    return s;
  };
}

const Ctx = createContext<{ lang: MenuLanguage; t: Translate }>({ lang: 'es', t: makeT('es') });

export function I18nProvider({ lang, children }: { lang: MenuLanguage; children: ReactNode }) {
  return <Ctx.Provider value={{ lang, t: makeT(lang) }}>{children}</Ctx.Provider>;
}

export const useI18n = () => useContext(Ctx);
